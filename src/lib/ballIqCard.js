/**
 * The full card model.
 * @param catStats  per-key records
 * @param _priorAcc accepted for older call sites; unused (the overall is derived here)
 * @param lifetime  {c, a} raw lifetime totals — tops up a legacy record, see overallScore
 * @param pinnedLeague  the player's CHOSEN league face (a LEAGUE_FACES cat), or
 *                      undefined to let the card pick their most-played one
 */
// ⚠️ `u` IS IN THIS LIST AND MUST STAY. It holds every answer we have a record
// of but no difficulty grade for — 4,384 of the 4,825 in the live log, because
// Daily 7 only began storing `diff` this month. Leaving it out (as this did
// until 2026-09-10) silently dropped 91% of the evidence on the way to a face:
// the WORLD and LEGENDS faces on a 299-answer card read as if they had none.
function mergeD(a, b) {
  if (!a && !b) return null;
  const out = {};
  for (const k of ["e", "m", "h", "u"]) {
    const x = Array.isArray(a?.[k]) ? a[k] : [0, 0], y = Array.isArray(b?.[k]) ? b[k] : [0, 0];
    if (x[1] || y[1]) out[k] = [(x[0] || 0) + (y[0] || 0), (x[1] || 0) + (y[1] || 0)];
  }
  return Object.keys(out).length ? out : null;
}

export function computeCard(catStats = {}, _priorAcc, lifetime, pinnedLeague) {
  // Fold aliases into their face BEFORE reading, so a profile carrying both
  // `ChampionsLeague` and `UCL` (46 in prod) rates one Champions League.
  // The player's own league keeps its slot; every OTHER league folds into Clubs
  // for this render only. Nothing is written back, so the fold is reversible
  // and a league face can change without losing a single answer.
  const leagueCat = pickLeagueFace(catStats, pinnedLeague).cat;
  const folded = {};
  for (const [k, v] of Object.entries(catStats || {})) {
    if (EXCLUDED_CATS.has(k)) continue;   // see EXCLUDED_CATS — not knowledge
    const key = k === leagueCat ? k : (LEAGUE_CATS.has(k) ? "Clubs" : (FACE_ALIAS[k] || k));
    const cur = folded[key] || { s: 0, n: 0, rc: 0, rn: 0, c: 0, a: 0 };
    // ⚠️ SCORE EACH MEMBER, THEN SUM — and the sum is the ONLY score the
    // folded record carries. It deliberately keeps `d` and `c`/`a` too, for
    // rawAnswered's gates and the progress bar, which means the record holds
    // the same evidence twice over. scoreOf therefore reads s/n FIRST: when
    // this pre-summed form was scored from its raw halves instead, it counted
    // the merged `d` (then missing `u`) against a summed `a` and discarded the
    // correct total — a 299-answer card came out at 50 instead of 55.
    const sk = scoreOf(v);
    const rk = rawScoreOf(v);   // the same members, unweighted — see rawScoreOf
    const d = mergeD(cur.d, v?.d);
    folded[key] = { s: cur.s + sk.s, n: cur.n + sk.n, rc: cur.rc + rk.c, rn: cur.rn + rk.n,
      c: cur.c + (v?.c || 0), a: cur.a + (v?.a || 0), ...(d ? { d } : {}) };
  }
  // Legacy = no raw key carries per-answer scores yet; only then does the
  // lifetime top-up apply (see overallScore).
  // A legacy record (no key scored yet) is rated WITH its lifetime top-up
  // spread across its keys — the same view recordAnswers will materialise.
  const rated = isScored(catStats) ? folded : withLegacyTopUp(folded, lifetime);
  const { mean, answered: answeredTotal } = overallScore(rated);
  const acc = mean / AVG_MULT;
  const overall = ratingFromScore(mean);
  const ratings = cardCompsFor(catStats, pinnedLeague).map(comp => {
    const cs = rated[comp.cat];
    // Gates count the league's OWN answers (raw), never borrowed ones.
    const answered = rawAnswered(cs);
    return {
      abbr: comp.abbr, cat: comp.cat, name: comp.name, short: comp.short || comp.name, icon: comp.icon, color: comp.color,
      rating: compRating(cs, acc),
      answered,
      // Per-face honesty: a face prints FULLY only from its own data; from
      // PROVISIONAL_ANSWERS it prints muted (see the constant).
      rated: answered >= MIN_RATED_ANSWERS,
      provisional: answered >= PROVISIONAL_ANSWERS && answered < MIN_RATED_ANSWERS,
    };
  });
  // `rated` travels WITH the card so every consumer inherits one answer to
  // "is there enough data to print a number?". Four surfaces once asked it four
  // ways and three got it wrong (a friend card printed 85 · GOLD off one
  // answer; the OG unfurl published six invented ratings).
  // Right / answered over the same records the rating is built from. `null`
  // when there is nothing to divide, so a caller can tell "no data" from 0%.
  let rc = 0, rn = 0;
  for (const cs of Object.values(rated)) { const r = rawScoreOf(cs); rc += r.c; rn += r.n; }
  return {
    ratings, overall, tier: cardTier(overall), answeredTotal,
    rated: answeredTotal >= MIN_RATED_ANSWERS,
    accuracy: acc,
    rawAccuracy: rn > 0 ? rc / rn : null,
    rawAnswered: rn,
    mean,
    calibration: { measured: CALIBRATION.measured, n: CALIBRATION.n },
  };
}

/**
 * What a round did to the card, for the results screen: overall before/after
 * and every face that moved. Pure — both sides are computeCard() over the
 * records the writer had before and after recordAnswers().
 */
export function cardDelta(prevCatStats, nextCatStats, prevLifetime, nextLifetime) {
  const before = computeCard(prevCatStats || {}, undefined, prevLifetime);
  const after = computeCard(nextCatStats || {}, undefined, nextLifetime);
  const faces = after.ratings
    .map((r, i) => ({ abbr: r.abbr, name: r.name, color: r.color, before: before.ratings[i].rating, after: r.rating,
                       shown: r.rated || r.provisional, wasShown: before.ratings[i].rated || before.ratings[i].provisional }))
    .filter(f => f.shown && (f.before !== f.after || !f.wasShown));
  return {
    before: before.overall, after: after.overall, ratedBefore: before.rated, ratedAfter: after.rated,
    answered: after.answeredTotal, toRated: Math.max(0, MIN_RATED_ANSWERS - Math.floor(after.answeredTotal)),
    faces,
  };
}

// ── THE SHARE LINE ────────────────────────────────────────────────────────────
// "My Ball IQ is 68. Can you beat me?" led with the one number that means the
// least to a stranger. The share leads with the strongest league — the thing
// worth bragging about — and, when the last round moved it today, the move.
const DELTA_KEY = "biq_last_card_delta";
const dayKey = () => { const d = new Date(); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`; };

/** Remember what the last round did (the writer calls this); read back the same day only. */
export function storeCardDelta(delta) {
  try { if (delta) localStorage.setItem(DELTA_KEY, JSON.stringify({ day: dayKey(), delta })); } catch { /* ignore */ }
}
export function readCardDelta() {
  try {
    const v = JSON.parse(localStorage.getItem(DELTA_KEY) || "null");
    return v && v.day === dayKey() ? v.delta : null;
  } catch { return null; }
}

/** One line for the share sheet. Unrated cards say so; rated ones lead with the best face. */
export function shareLine(card, delta = null, appName = "Ball IQ") {
  if (!card || !card.rated) return `Can you beat me at ${appName}? ⚽`;
  const faces = card.ratings.filter(r => r.rated).sort((a, b) => b.rating - a.rating);
  const best = faces[0];
  const moved = delta && delta.ratedAfter && delta.faces && delta.faces.find(f => f.after > f.before);
  const head = best ? `${appName} ${card.overall} · ${best.abbr} ${best.rating}` : `${appName} ${card.overall}`;
  const move = moved ? ` — ${moved.abbr} ${moved.before} → ${moved.after} today` : "";
  return `${head}${move}. Can you beat me? ⚽`;
}

