// Bank categories that ARE a face under another name. `ChampionsLeague` is a
// legacy key still present in 46 prod profiles beside `UCL`; `Euros` is
// international football and belongs with the World Cup on the INT face.
export const FACE_ALIAS = { ChampionsLeague: "UCL", Euros: "WorldCup" };

const FACE_CATS = new Set(CARD_COMPS.map(c => c.cat));

/**
 * Which face an answer feeds, or null (overall only).
 * Order: the answer's real category (club quiz carries it as `realCat` beside
 * the UI re-tag), then an alias, then the club's league.
 */
export function faceCatFor(ans) {
  if (!ans) return null;
  const cat = ans.realCat || ans.cat;
  if (FACE_CATS.has(cat)) return cat;
  if (FACE_ALIAS[cat]) return FACE_ALIAS[cat];
  if (ans.club && CLUB_NAME_TO_COMP[ans.club]) return CLUB_NAME_TO_COMP[ans.club];
  return null;
}

/**
 * The card face a QUIZ CATEGORY builds, as the abbreviation printed on the
 * card ("EPL", "INT"), or null when that category feeds no face.
 *
 * ⚠️ THE LEAGUE PICKER MUST NOT PROMISE A RATING THAT DOES NOT EXIST. Its
 * rows printed `Builds your ${abbr} rating` off the PICKER's own abbr for
 * every row, and the picker carries thirteen entries against the card's six
 * faces — so seven rows advertised an L1 / TSL / PRI / LEG / MGR / REC
 * rating that is nowhere in the app, and Euros promised "EUR" when its
 * answers land on INT. Only five of thirteen rows were true. Deriving the
 * copy from CARD_COMPS is what makes the picker's claim un-rottable: add a
 * league without a face and it now says the honest thing by itself.
 * (Found in the simulator 2026-09-09.)
 */
export function faceAbbrForCat(cat) {
  const face = FACE_CATS.has(cat) ? cat : (FACE_ALIAS[cat] || null);
  if (!face) return null;
  return (CARD_COMPS.find(c => c.cat === face) || {}).abbr || null;
}

// A face with fewer than MIN_RATED_ANSWERS but at least this many prints a
// PROVISIONAL number — muted, never the accented "best" — instead of a bar.
// Alex, 2026-09-09, seeing La Liga / Bundesliga / Serie A as three bars after
// they had carried numbers: "where is the rating? in the shadow realms? it
// can not vanish like this". He is right about the feel: a number that was
// there and then is not reads as a loss, whatever the gate's statistics. Three
// answers is where the number stops being pure prior; shrinkage toward the
// overall (weight 2) keeps it believable until ten.
export const PROVISIONAL_ANSWERS = 3;

// Prior weight, in answers, for the overall — how many answers the population
// median "counts as" before the player's own record takes over.
//
// TWENTY, NOT TEN, AND THE DIRECTION IS THE POINT. The calibrated scale is
// steep where players actually live (0.58 → 65, 0.82 → 93: 28 points across
// 0.24 of accuracy), so at ten answers the noise in a record is ±15 rating
// points. Simulated with weight 10, a lucky 8/10 start printed 79 · GOLD, then
// slid to 71 · SILVER over the next thirty answers at a true 65% — the exact
// "it keeps going down" a real player reported. With weight 20 the same run
// prints 73 and settles at 70: a three-point correction, no tier flip. And a
// STEADY above-median player now RISES toward their level (68 → 72 → 75)
// rather than starting above it and falling. Shrinkage toward the median is
// honest — with little evidence you are assumed near the middle — and it makes
// the common experience "the more I play, the more it reflects me", which is
// the only direction a rating should surprise in. Twenty ≈ two club quizzes.
export const PRIOR_WEIGHT = 20;

/** Multiplier a correct answer earns, by difficulty. Unknown labels count as medium. */
export const MULT = CALIBRATION.mult;
export const AVG_MULT = CALIBRATION.avgMult;
/** The measured median player's rating, as a fraction (≈0.64): where a card with no evidence starts. */
export const BASELINE = CALIBRATION.baseline;
export function multFor(diff) { return MULT[diff] ?? MULT.medium; }

/** Mean score (0…1.2) → 40-99. Linear: 0.61 → 61. Capped at 99 — perfect on hard is 120. */
export function ratingFromScore(mean) {
  const x = Number.isFinite(mean) ? mean : BASELINE;
  return Math.max(40, Math.min(99, Math.round(x * 100)));
}

/** Kept for the calibration tests and any caller that thinks in accuracy: an average-difficulty record. */
export function ratingFromAccuracy(acc) {
  return ratingFromScore((Number.isFinite(acc) ? acc : CALIBRATION.median) * AVG_MULT);
}

/**
 * A key's score record. New writes carry {s, n} (decayed score sum and
 * answer count). A legacy {c, a} converts as s = AVG_MULT·c — exact for a
 * record of average difficulty; both may be present after the upgrade.
 */
export function scoreOf(cs) {
  if (!cs) return { s: 0, n: 0 };
  if (Number.isFinite(cs.s) && Number.isFinite(cs.n) && cs.n > 0) return { s: cs.s, n: cs.n };
  const c = cs.c || 0, a = cs.a || 0;
  return { s: AVG_MULT * c, n: a };
}
// The name the writer imported earlier today; same function.
export const skillOf = scoreOf;

// A LEGACY RECORD IS TOPPED UP FROM THE LIFETIME TOTALS, ONCE. catStats began
// decaying on 2026-09-01 (0.98 per answer), so by the 9th every account's
// per-category record was its last ~100 answers — Alex's read 55/106, a 52%
// window, beside a Scouting Report saying "Accuracy 61%" from the same
// lifetime totals. Scored under the new model that window printed 58 ·
// BRONZE. Two true records, one card: until a record carries per-answer
// scores (s/n), the answers the window has forgotten are counted back in at
// the lifetime accuracy — as average difficulty, capped at LIFETIME_TOPUP so
// the card stays dynamic once new answers arrive. Once any key carries s/n
// the top-up stops: from there the card is the player's own scored answers.
export const LIFETIME_TOPUP = 300;

/** The lifetime top-up for a legacy record, or null. {s, n} in score units. */
export function legacyTopUp(catStats = {}, lifetime) {
  if (!lifetime || !(lifetime.a > 0) || !(lifetime.c >= 0) || lifetime.c > lifetime.a) return null;
  let n = 0;
  for (const cs of Object.values(catStats || {})) n += scoreOf(cs).n;
  if (lifetime.a <= n) return null;
  const extra = Math.min(LIFETIME_TOPUP, lifetime.a - n);
  return { s: AVG_MULT * (lifetime.c / lifetime.a) * extra, n: extra };
}

/**
 * Spread a legacy record's lifetime top-up across its keys IN PROPORTION to
 * each key's own answers, returning a new map (c/a untouched). Alex, on build
 * 117: "the ratings on the card went down but the overall went up? the
 * individual ratings also have to be boosted". The top-up used to live on a
 * single overall-only key, so the overall carried ~200 answers the faces
 * never saw and sat ABOVE every rated league — arithmetic no player can
 * follow. Proportional spreading keeps overall = answers-weighted mean of the
 * keys, keeps each league's ORDER (the weak league stays weakest), and gates
 * stay on the key's OWN answers (`a`), so a four-answer league does not become
 * "rated" by borrowed ones.
 */
export function withLegacyTopUp(catStats = {}, lifetime) {
  const top = legacyTopUp(catStats, lifetime);
  if (!top) return catStats;
  let N = 0;
  for (const cs of Object.values(catStats || {})) N += scoreOf(cs).n;
  if (!(N > 0)) return catStats;
  const out = {};
  for (const [k, cs] of Object.entries(catStats || {})) {
    const own = scoreOf(cs);
    const share = own.n / N;
    out[k] = { ...cs, s: own.s + top.s * share, n: own.n + top.n * share };
  }
  return out;
}

/**
 * A key's RAW answer count for the print gates. Since the writer keeps raw
 * per-difficulty counts in `d`, those are the truth; a legacy record falls
 * back to its (decayed) `a`. ⚠️ Gates must not read the decayed `a` on scored
 * records: with decay 0.995 the tenth answer leaves `a` at 9.78 and "10 to
 * get rated" never reaches zero.
 */
export function rawAnswered(cs) {
  if (!cs) return 0;
  const d = cs.d;
  let fromD = 0;
  if (d && typeof d === "object") {
    for (const k of ["e", "m", "h"]) fromD += (Array.isArray(d[k]) ? (d[k][1] || 0) : 0);
  }
  // ⚠️ THE MAX OF BOTH, NEVER `d` ALONE. `d` counts only answers recorded
  // since the 2026-09-09 rebuild; `a` is the decayed running count and
  // carries everything before it. Preferring `d` the moment it existed meant
  // ONE new answer replaced a whole legacy history with "1" — so a face with
  // forty answers behind it, printing a rating, went to a DASH the moment its
  // owner played it. Alex on build 125: "4 of the items on the scorecard are
  // gone, this was never an issue in 1.7.2." Reproduced exactly: INT 72 → —
  // after a single CORRECT answer.
  //
  // Both terms are needed, which is why this is a max and not a swap back:
  //   · `a` alone never opens the gate for a NEW player — decay leaves it at
  //     9.78 after ten answers, so the tenth never rates them (the bug `d`
  //     was introduced to fix).
  //   · `d` alone discards every pre-rebuild answer, which is this bug.
  // max() satisfies both, and it makes the invariant structural: playing a
  // category can only ever raise its answer count.
  return Math.max(fromD, cs.a || 0);
}

/** True once any key carries per-answer scores (the record is no longer legacy). */
export function isScored(catStats = {}) {
  return Object.values(catStats || {}).some(v => Number.isFinite(v?.s) && Number.isFinite(v?.n) && v.n > 0);
}

// Per-answer decay of every key's score record. 0.995: half-life ~140
// answers — the card reflects "you", moves within a fortnight of daily play.
export const CAT_DECAY = 0.995;

/**
 * THE WRITER. Folds a finished round's answers into catStats and returns the
 * new map. Lives here, not in App.jsx, so the arithmetic that decides every
 * card is unit-tested beside the model that reads it.
 *
 * - each answer scores (correct ? MULT[diff] : 0) into its key's {s, n}; {c, a}
 *   keep being written as plain decayed counts (progress bar, merge, older
 *   clients); `d` keeps RAW per-difficulty counts for the next calibration.
 * - a key is filed under the face it feeds (faceCatFor), else its real cat.
 * - ON THE FIRST SCORED WRITE a legacy record's lifetime top-up (see
 *   legacyTopUp) is MATERIALISED as the `_legacy` key and thereafter decays
 *   like every other key. Without this the top-up vanished at the first scored
 *   quiz and ten hard rights LOWERED a card from 65 to 63 — the exact
 *   "it goes down the more I play" this whole day was about.
 */
export function recordAnswers(prevCatStats = {}, answers = [], lifetime) {
  const catStats = { ...(prevCatStats || {}) };
  const list = (answers || []).filter(a => a && a.cat);
  if (!list.length) return catStats;
  // ON THE FIRST SCORED WRITE a legacy record's lifetime top-up is spread
  // into its keys (see withLegacyTopUp) — materialised, so it decays with
  // every later answer instead of vanishing. As a switch it vanished at the
  // first scored quiz and ten hard rights LOWERED a card 65 → 63.
  let base = catStats;
  if (!isScored(catStats)) base = withLegacyTopUp(catStats, lifetime);
  const outStats = { ...base };
  for (const ans of list) {
    const key = faceCatFor(ans) || ans.cat;
    const cur = outStats[key] || { c: 0, a: 0 };
    const ok = ans.isCorrect ? 1 : 0;
    const diff = (ans.diff === "easy" || ans.diff === "hard") ? ans.diff : "medium";
    const prev = scoreOf(cur); // a legacy {c,a} converts once, here, then carries s/n
    const d = { ...(cur.d || {}) };
    const dk = diff[0];
    d[dk] = [((d[dk] || [0, 0])[0] || 0) + ok, ((d[dk] || [0, 0])[1] || 0) + 1];
    outStats[key] = {
      c: (cur.c || 0) * CAT_DECAY + ok,
      a: (cur.a || 0) * CAT_DECAY + 1,
      s: prev.s * CAT_DECAY + (ok ? multFor(diff) : 0),
      n: prev.n * CAT_DECAY + 1,
      d,
    };
  }
  return outStats;
}

/**
 * The player's overall — every category, shrunk toward the population
 * baseline with PRIOR_WEIGHT answers of weight. `lifetime` = {c, a} raw
 * totals (totalCorrect / totalAnswered), used only to top up a legacy record.
 */
export function overallScore(catStats = {}, lifetime) {
  // ⚠️ The caller decides whether `lifetime` applies (computeCard passes it
  // only while NO raw key carries s/n). It cannot be decided here: computeCard
  // folds aliases first, and the fold writes s/n onto every key.
  let s = 0, n = 0, own = 0;
  for (const cs of Object.values(catStats || {})) { const k = scoreOf(cs); s += k.s; n += k.n; own += rawAnswered(cs); }
  void lifetime; // spread by computeCard via withLegacyTopUp before this is called
  return { mean: (s + BASELINE * PRIOR_WEIGHT) / (n + PRIOR_WEIGHT), answered: own };
}

/** Kept for callers that think in accuracy. */
export function overallAccuracy(catStats = {}) {
  const { mean, answered } = overallScore(catStats);
  return { acc: mean / AVG_MULT, answered };
}

// One face. Shrunk toward the player's OVERALL mean with weight 2 — the right
// prior for "how would they do in this league" — but a face is only PRINTED
// from PROVISIONAL_ANSWERS (muted) and fully from MIN_RATED_ANSWERS.
// ⚠️ Nothing sums faces to make the overall; see overallScore().
export function compRating(cs, priorAcc = CALIBRATION.median) {
  const { s, n } = scoreOf(cs);
  const p = Number.isFinite(priorAcc) ? priorAcc : CALIBRATION.median;
  const priorMean = Math.max(0.25, Math.min(0.75, p)) * AVG_MULT;
  return ratingFromScore((s + priorMean * 2) / (n + 2));
}

