/** The lifetime top-up for a legacy record, or null. {s, n} in score units. */
export function legacyTopUp(catStats = {}, lifetime) {
  if (!lifetime || !(lifetime.a > 0) || !(lifetime.c >= 0) || lifetime.c > lifetime.a) return null;
  // ⚠️ A MISSING totalCorrect IS NOT ZERO CORRECT. 130 of 308 prod profiles
  // carry `totalAnswered` with `totalCorrect` NULL, and every caller writes
  // `stats.totalCorrect || 0` — so those cards topped themselves up with a
  // lifetime record asserting NONE RIGHT out of a thousand answered, and every
  // rating was dragged toward the floor. Alex, seeing a friend's card: "there
  // is no way he has all those stats under 50." He was right: that player read
  // 67 with faces 49/40/40/55/40/51, and 73 with 53/43/40/60/40/55 once this
  // stopped counting. A lifetime with answers but no correct count is MISSING
  // DATA — the only honest thing to do is not top up at all.
  if (lifetime.a >= 1 && !(lifetime.c > 0)) return null;
  let n = 0;
  for (const cs of Object.values(catStats || {})) n += scoreOf(cs).n;
  if (lifetime.a <= n) return null;
  const extra = Math.min(LIFETIME_TOPUP, lifetime.a - n);
  return { s: AVG_MULT * (lifetime.c / lifetime.a) * extra, n: extra };
}

/**
 * Spread a legacy record's lifetime top-up across its keys IN PROPORTION to
 * each key's own answers, returning a new map (c/a untouched). Alex, on build
 * 117: "the ratings on the card went down but the overall went up? the
 * individual ratings also have to be boosted". The top-up used to live on a
 * single overall-only key, so the overall carried ~200 answers the faces
 * never saw and sat ABOVE every rated league — arithmetic no player can
 * follow. Proportional spreading keeps overall = answers-weighted mean of the
 * keys, keeps each league's ORDER (the weak league stays weakest), and gates
 * stay on the key's OWN answers (`a`), so a four-answer league does not become
 * "rated" by borrowed ones.
 */
/**
 * The same spread, MATERIALISED as raw counts instead of a parallel score.
 *
 * Used by recordAnswers on the first write to a legacy record. withLegacyTopUp
 * above is a READ-TIME view: it writes s/n, which is right for computeCard
 * (transient, thrown away each render) and wrong to store, because since
 * 2026-09-10 s/n means "pre-summed by the fold" and outranks raw counts — a
 * stored top-up would win over every answer played afterwards and a perfect
 * round would LOWER the card. That is the "ten hard rights took me 65 → 63"
 * bug, and its unit test caught this the moment scoreOf changed.
 *
 * A top-up is by definition "this many more answers, at the player's lifetime
 * accuracy, at average difficulty" — which is precisely what the `u` bucket
 * says. Storing it there needs no second representation, and ROUNDS: `d` holds
 * whole questions, and keeping it integral is the point of the whole rebuild.
 */
export function materialiseLegacyTopUp(catStats = {}, lifetime) {
  const topped = withLegacyTopUp(catStats, lifetime);
  if (topped === catStats) return catStats;
  const out = {};
  for (const [k, cs] of Object.entries(topped)) {
    const own = scoreOf(catStats[k]);
    const dn = Math.round((cs.n || 0) - own.n);
    const dc = Math.round(((cs.s || 0) - own.s) / AVG_MULT);
    const { s: _s, n: _n, ...rest } = cs;
    if (dn <= 0) { out[k] = rest; continue; }
    const d = { ...(rest.d || {}) };
    const cur = Array.isArray(d.u) ? d.u : [0, 0];
    d.u = [(cur[0] || 0) + Math.max(0, Math.min(dn, dc)), (cur[1] || 0) + dn];
    out[k] = { ...rest, d };
  }
  return out;
}

export function withLegacyTopUp(catStats = {}, lifetime) {
  const top = legacyTopUp(catStats, lifetime);
  if (!top) return catStats;
  let N = 0;
  for (const cs of Object.values(catStats || {})) N += scoreOf(cs).n;
  if (!(N > 0)) return catStats;
  const out = {};
  for (const [k, cs] of Object.entries(catStats || {})) {
    const own = scoreOf(cs);
    const share = own.n / N;
    out[k] = { ...cs, s: own.s + top.s * share, n: own.n + top.n * share };
  }
  return out;
}

/**
 * A key's RAW answer count for the print gates. Since the writer keeps raw
 * per-difficulty counts in `d`, those are the truth; a legacy record falls
 * back to its (decayed) `a`. ⚠️ Gates must not read the decayed `a` on scored
 * records: with decay 0.995 the tenth answer leaves `a` at 9.78 and "10 to
 * get rated" never reaches zero.
 */
export function rawAnswered(cs) {
  if (!cs) return 0;
  const d = cs.d;
  let fromD = 0;
  if (d && typeof d === "object") {
    for (const k of ["e", "m", "h", "u"]) fromD += (Array.isArray(d[k]) ? (d[k][1] || 0) : 0);
  }
  // ⚠️ THE MAX OF BOTH, NEVER `d` ALONE. `d` counts only answers recorded
  // since the 2026-09-09 rebuild; `a` is the decayed running count and
  // carries everything before it. Preferring `d` the moment it existed meant
  // ONE new answer replaced a whole legacy history with "1" — so a face with
  // forty answers behind it, printing a rating, went to a DASH the moment its
  // owner played it. Alex on build 125: "4 of the items on the scorecard are
  // gone, this was never an issue in 1.7.2." Reproduced exactly: INT 72 → —
  // after a single CORRECT answer.
  //
  // Both terms are needed, which is why this is a max and not a swap back:
  //   · `a` alone never opens the gate for a NEW player — decay leaves it at
  //     9.78 after ten answers, so the tenth never rates them (the bug `d`
  //     was introduced to fix).
  //   · `d` alone discards every pre-rebuild answer, which is this bug.
  // max() satisfies both, and it makes the invariant structural: playing a
  // category can only ever raise its answer count.
  return Math.max(fromD, cs.a || 0);
}

/** True once any key carries per-answer scores (the record is no longer legacy). */
/**
 * Does this record carry per-category evidence of its own?
 *
 * The answer decides whether computeCard spreads the LIFETIME top-up across
 * the faces (a legacy record, where all we know is one global total) or reads
 * the record's own numbers. Get it wrong in the "no" direction and every
 * player's six faces print the same number forever.
 *
 * ⚠️ IT MUST TEST BOTH SCHEMES. This asked only about `s`/`n` and became
 * permanently false the moment recordAnswers stopped deriving them
 * (2026-09-10) — every card in the app would have fallen back to the top-up
 * for good, which is the "all six items read 55" shape Alex has already been
 * shown once. Raw `d` counts are now the primary evidence and s/n the legacy
 * one; either counts.
 */
export function isScored(catStats = {}) {
  return Object.values(catStats || {}).some(v =>
    (Number.isFinite(v?.s) && Number.isFinite(v?.n) && v.n > 0) ||
    (v?.d && typeof v.d === "object" && ["e", "m", "h", "u"].some(k => Array.isArray(v.d[k]) && (v.d[k][1] || 0) > 0))
  );
}

// Per-answer decay of every key's score record. 0.995: half-life ~140
// answers — the card reflects "you", moves within a fortnight of daily play.
export const CAT_DECAY = 0.995;

/**
 * THE WRITER. Folds a finished round's answers into catStats and returns the
 * new map. Lives here, not in App.jsx, so the arithmetic that decides every
 * card is unit-tested beside the model that reads it.
 *
 * - each answer adds 1 to its key's RAW `d` bucket for that difficulty. That
 *   is the whole write: {s,n} are no longer derived and {c,a} are frozen at
 *   whatever a legacy record already carried (see the note in the loop).
 * - a key is filed under the face it feeds (faceCatFor), else its real cat.
 * - ON THE FIRST SCORED WRITE a legacy record's lifetime top-up (see
 *   legacyTopUp) is MATERIALISED as the `_legacy` key and thereafter decays
 *   like every other key. Without this the top-up vanished at the first scored
 *   quiz and ten hard rights LOWERED a card from 65 to 63 — the exact
 *   "it goes down the more I play" this whole day was about.
 */
export function recordAnswers(prevCatStats = {}, answers = [], lifetime) {
  const catStats = { ...(prevCatStats || {}) };
  const list = (answers || []).filter(a => a && a.cat);
  if (!list.length) return catStats;
  // ON THE FIRST SCORED WRITE a legacy record's lifetime top-up is spread
  // into its keys (see withLegacyTopUp) — materialised, so it decays with
  // every later answer instead of vanishing. As a switch it vanished at the
  // first scored quiz and ten hard rights LOWERED a card 65 → 63.
  let base = catStats;
  if (!isScored(catStats)) base = materialiseLegacyTopUp(catStats, lifetime);
  const outStats = { ...base };
  for (const ans of list) {
    const key = faceCatFor(ans) || ans.cat;
    const cur = outStats[key] || { c: 0, a: 0 };
    const ok = ans.isCorrect ? 1 : 0;
    const diff = (ans.diff === "easy" || ans.diff === "hard") ? ans.diff : "medium";
    // ⚠️ ONLY `d` IS WRITTEN NOW — raw integer counts, no decay, no derived
    // s/n. The old writer fed scoreOf's output back through CAT_DECAY, which
    // is what produced "26.78 correct": a number that is not a count, cannot
    // be shown to a player, and SATURATES at 200 answers however much they
    // play. Alex: "how do you answer 26.78 questions right with decimals?"
    //
    // Existing c/a are left EXACTLY as they are. scoreOf reads the exact part
    // from `d` and lets the frozen decayed totals carry only whatever they
    // still claim beyond it, so the estimated share shrinks with every answer
    // and a card becomes fully verifiable on its own. Freezing them rather
    // than deleting them is the same rule as rawAnswered's: never throw away
    // history you cannot reconstruct.
    const d = { ...(cur.d || {}) };
    const dk = diff[0];
    d[dk] = [((d[dk] || [0, 0])[0] || 0) + ok, ((d[dk] || [0, 0])[1] || 0) + 1];
    outStats[key] = { ...cur, d };
  }
  return outStats;
}

/**
 * The SAME evidence scoreOf reads, but unweighted: how many questions this
 * record got right, out of how many it answered.
 *
 * This exists so the Profile's "Accuracy" tile can be sourced from the answers
 * themselves instead of the lifetime counters, which are historically
 * inflated: `saveStats` added `newResult.score` to `totalCorrect` for EVERY
 * mode, and in four of them `score` is not a count of correct answers
 * (mp:race 29,584% of questions, mystery 2,606%, footle 358%, trail 126%).
 * 26,081 of the 32,769 "correct answers" the app has ever counted came from
 * those four. The writer is gated now, but every historic total is still
 * wrong, and a wrong 67% sitting beside an honest card is what made a real
 * player's card look broken when it was the only truthful number on screen.
 *
 * catStats is quiz-only — Footle, Trail, Mystery and multiplayer never write a
 * category here — so this is the app's one clean accuracy.
 *
 * ⚠️ NOT `rating / AVG_MULT`. That is the difficulty-ADJUSTED equivalent and
 * would print a number no player can check against their own answers. A tile
 * labelled "Accuracy" has to mean right ÷ answered. The rating sitting ABOVE
 * it is the point: it is higher because hard questions are worth more.
 */
export function rawScoreOf(cs) {
  if (!cs) return { c: 0, n: 0 };
  // pre-summed by computeCard's fold, exactly as scoreOf's s/n branch
  if (Number.isFinite(cs.rc) && Number.isFinite(cs.rn) && cs.rn > 0) return { c: cs.rc, n: cs.rn };
  let c = 0, n = 0;
  const d = cs.d;
  if (d && typeof d === "object") {
    for (const k of ["e", "m", "h", "u"]) {
      const b = d[k];
      if (!Array.isArray(b)) continue;
      c += (b[0] || 0); n += (b[1] || 0);
    }
  }
  const a = cs.a || 0, cc = cs.c || 0;
  const extra = a - n;
  if (extra > 0 && a > 0) { c += (cc / a) * extra; n += extra; }
  return { c, n };
}

/**
 * The player's overall — every category, shrunk toward the population
 * baseline with PRIOR_WEIGHT answers of weight. `lifetime` = {c, a} raw
 * totals (totalCorrect / totalAnswered), used only to top up a legacy record.
 */
export function overallScore(catStats = {}, lifetime) {
  // ⚠️ The caller decides whether `lifetime` applies (computeCard passes it
  // only while NO raw key carries s/n). It cannot be decided here: computeCard
  // folds aliases first, and the fold writes s/n onto every key.
  let s = 0, n = 0, own = 0;
  for (const cs of Object.values(catStats || {})) { const k = scoreOf(cs); s += k.s; n += k.n; own += rawAnswered(cs); }
  void lifetime; // spread by computeCard via withLegacyTopUp before this is called
  return { mean: (s + BASELINE * PRIOR_WEIGHT) / (n + PRIOR_WEIGHT), answered: own };
}

/** Kept for callers that think in accuracy. */
export function overallAccuracy(catStats = {}) {
  const { mean, answered } = overallScore(catStats);
  return { acc: mean / AVG_MULT, answered };
}

// One face. Shrunk toward the player's OVERALL mean with weight 2 — the right
// prior for "how would they do in this league" — but a face is only PRINTED
// from PROVISIONAL_ANSWERS (muted) and fully from MIN_RATED_ANSWERS.
// ⚠️ Nothing sums faces to make the overall; see overallScore().
// ⚠️ A FACE IS DAMPED LESS THAN THE OVERALL, DELIBERATELY — but not by 2.
// This was a bare `2` while the overall uses PRIOR_WEIGHT (20), which is a
// tenth of the damping on a tenth of the data: a face printed 99 from eight
// answers and 40 from three, then drifted. That is the "kept getting lower"
// shape from Alex's very first device review, and it was visible on a real
// rendered card (the WORLD face printing 99 off eight PL answers).
//
// The two weights differ on purpose. The overall pools every answer, so 20 is
// a small correction there; a face holds tens of answers, where 20 would
// dominate — at that weight a perfect 8/8 and a solid 30/40 both read 77 and
// the card stops saying where you are strong, which is its whole job. 8 puts
// a face at the 10-answer gate on roughly 55% its own evidence: enough to
// listen to the player, enough to stop a hot streak printing 99.
//   8/8 -> 87 (was 99) · 9/10 -> 83 (93) · 3/10 -> 47 (40) · 30/40 -> 79 (82)
export const FACE_PRIOR_WEIGHT = 8;
export function compRating(cs, priorAcc = CALIBRATION.median) {
  const { s, n } = scoreOf(cs);
  const p = Number.isFinite(priorAcc) ? priorAcc : CALIBRATION.median;
  const priorMean = Math.max(0.25, Math.min(0.75, p)) * AVG_MULT;
  return ratingFromScore((s + priorMean * FACE_PRIOR_WEIGHT) / (n + FACE_PRIOR_WEIGHT));
}

