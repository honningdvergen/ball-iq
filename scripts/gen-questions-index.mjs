// gen-questions-index.mjs — emit src/questions-index.js from the question bank.
//
//   node scripts/gen-questions-index.mjs           # write
//   node scripts/gen-questions-index.mjs --check   # exit 1 if stale (CI use)
//
// WHY THIS EXISTS
//
// src/questions.js is 2.1MB raw / 623kB gzipped and parses in ONE ~700ms
// main-thread task. That task was landing at t≈2s — exactly while a visitor is
// deciding whether to tap — and it is the entire "INP needs improvement" in
// Clarity. (JSON.parse was tried 2026-07-29 and made it WORSE: 779ms vs 651ms
// and +286kB. The problem is volume, not encoding.)
//
// The insight is that BROWSING and PLAYING have different data needs. Every
// selection site in App.jsx filters on `type`, `club`, `cat` or `id` — never on
// question text — and the club/league pickers load the entire bank purely to
// render a count next to each tile. Nobody is playing at that point. This index
// carries the filterable fields and NO text: 435kB raw / ~47kB gzipped, a 13×
// reduction, so a count costs ~50ms instead of ~700ms.
//
// ORDER IS LOAD-BEARING. Rows are emitted in QB order and MUST stay that way:
// the Daily 7 shuffles by array position (seededShuffle over the mcq-filtered
// slice), so an index that reorders rows would silently hand different daily
// questions to anyone selecting via the index. Same class of bug as the
// Math.sin JSC-vs-V8 divergence — invisible, and wrong for months.
//
// Staleness is structurally impossible: `npm run dev` and `npm run build` both
// regenerate before anything reads it. The file is committed anyway so a fresh
// clone type-checks and the diff is reviewable.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'src/questions-index.js');
const CHECK = process.argv.includes('--check');

const { QB } = await import(resolve(ROOT, 'src/questions.js'));

// Only the fields something actually filters on. Adding a field here is cheap;
// adding question TEXT defeats the entire purpose of the file.
const rows = QB.map((q) => ({
  id: q?.id ?? null,
  type: q?.type ?? null,
  cat: q?.cat ?? null,
  club: q?.club ?? null,
  diff: q?.diff ?? null,
  // Option COUNT, not the options. Every call site pairs its type check with
  // `Array.isArray(q.o)` to reject malformed rows; `n === 4` is that same
  // predicate without shipping the strings.
  n: Array.isArray(q?.o) ? q.o.length : 0,
}));

const body = `// GENERATED by scripts/gen-questions-index.mjs — DO NOT EDIT.
// Filterable projection of src/questions.js with no question text.
// Row order matches QB exactly and is load-bearing (see the generator).
// ${rows.length} rows.
export const QB_INDEX = ${JSON.stringify(rows)};
`;

if (CHECK) {
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch {}
  if (current !== body) {
    console.error('✗ src/questions-index.js is STALE — run: node scripts/gen-questions-index.mjs');
    process.exit(1);
  }
  console.log(`✓ questions-index.js current (${rows.length} rows)`);
} else {
  writeFileSync(OUT, body);
  const kb = (n) => Math.round(n / 1024) + 'kB';
  console.log(`✓ questions-index.js — ${rows.length} rows, ${kb(body.length)} raw (bank is ${kb(readFileSync(resolve(ROOT, 'src/questions.js')).length)})`);
}
