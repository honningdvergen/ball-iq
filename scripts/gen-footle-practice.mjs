// Emits src/marketing/footlePractice.js — the practice puzzle + grader for
// the homepage Footle band.
//
// TWO RULES, both learned the expensive way:
//
// 1. THE ANSWER IS ALWAYS A PAST ONE. The mockup hardcoded ANSWER='ALISSON'
//    (flagged in the opportunity audit); today's answer would spoil the real
//    game. Same policy as /football-wordle/ (gen-seo-pages): walk backwards
//    from ~30 days into the frozen WORDLE_ANSWER_LOG, bounded by Footle #1 —
//    the unbounded version of this walk was a time bomb that killed 387 of
//    1,095 simulated future builds.
//
// 2. THE GRADER IS EMITTED FROM THE REAL ONE via toString(), never
//    reimplemented, so duplicate-letter scoring cannot drift from the app.
//    The guard below RE-IMPORTS THE EMITTED FILE and runs it against the
//    imported original on the cases that distinguish graders; any mismatch
//    fails the build. (Importing the artifact back is deliberately stronger
//    than eval-ing the string: it tests what the bundler will actually see.)
//
// The marketing chunk must NOT import src/lib/wordle.js directly — it carries
// the 400+ player list and the full answer log. This file emits one answer,
// one name, one number and one function.

import { readFileSync, writeFileSync, unlinkSync, existsSync } from 'fs';
import { pathToFileURL } from 'node:url';
import {
  getWordleDayIndex,
  getWordleAnswerForDayIndex,
  gradeWordleGuess,
  WORDLE_ANCHOR_DAY,
  WORDLE_ANSWER_LOG,
  WORDLE_FULL_NAMES,
} from '../src/lib/wordle.js';

const OUT = 'src/marketing/footlePractice.js';
const LOOKBACK = 30; // never fresher than ~a month

function pick() {
  const today = getWordleDayIndex();
  for (let back = LOOKBACK; ; back++) {
    const dayIndex = today - back;
    const number = dayIndex - WORDLE_ANCHOR_DAY + 1;
    if (number < 1) break; // bounded by Footle #1 — do not remove
    if (number > WORDLE_ANSWER_LOG.length) continue;
    const answer = getWordleAnswerForDayIndex(dayIndex);
    if (answer) return { answer, number };
  }
  console.error('[footle-practice] no past answer inside the log — refusing to emit');
  process.exit(1);
}

const { answer, number } = pick();
const todayNumber = getWordleDayIndex() - WORDLE_ANCHOR_DAY + 1;
if (number >= todayNumber) {
  console.error(`[footle-practice] picked #${number} but today is #${todayNumber} — not past`);
  process.exit(1);
}
// WORDLE_FULL_NAMES values are ARRAYS — ["Wesley","Sneijder"] — the same data
// shape behind the SNIJDER unwinnable-puzzle incident. Join, don't assume.
const fullRaw = WORDLE_FULL_NAMES[answer] || null;
const full = Array.isArray(fullRaw) ? fullRaw.join(' ') : fullRaw;
if (!full || typeof full !== 'string') {
  console.error(`[footle-practice] ${answer} has no usable full name — refusing`);
  process.exit(1);
}

const body = `// GENERATED by scripts/gen-footle-practice.mjs — do not edit.
// A PAST Footle puzzle (never today's) + the app's own grader, emitted via
// toString() so duplicate-letter scoring cannot drift from src/lib/wordle.js.

export const FP_ANSWER = '${answer}';
export const FP_FULL = '${full.replace(/'/g, "\\'")}';
export const FP_NUMBER = ${number};

export const gradeGuess = ${gradeWordleGuess.toString()};
`;

writeFileSync(OUT, body);

// Grader integrity: import the emitted artifact back and prove it matches the
// original on the cases that tell graders apart (duplicate letters both ways).
const emitted = await import(`${pathToFileURL(OUT).href}?v=${number}-${todayNumber}`);
for (const [g, a] of [['BANDANA', 'BANANAS'], ['BANANAS', 'BANDANA'], ['INITIAL', 'PLATINI'], ['LAPORTE', 'HAALAND']]) {
  const want = JSON.stringify(gradeWordleGuess(g, a));
  const got = JSON.stringify(emitted.gradeGuess(g, a));
  if (want !== got) {
    unlinkSync(OUT); // a wrong grader must not survive on disk
    console.error(`[footle-practice] emitted grader diverges on (${g},${a}) — gradeWordleGuess no longer survives toString()`);
    process.exit(1);
  }
}
if (emitted.FP_ANSWER !== answer || emitted.FP_NUMBER !== number) {
  unlinkSync(OUT);
  console.error('[footle-practice] emitted constants do not round-trip — refusing');
  process.exit(1);
}

console.log(`[footle-practice] wrote ${OUT} — No. ${number} (${answer}), ${todayNumber - number} days old, grader verified`);
