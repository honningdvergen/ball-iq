// Writes src/design/tokens.css from src/design/tokens.js.
//
// The app entry (src/main.jsx) cannot import a .js module for its CSS, and the
// marketing homepage cannot import app.css -- it renders WITHOUT App.jsx, on
// purpose, so marketing visitors never download the game bundle or its 211KB
// stylesheet (main.jsx:200). That left the homepage with no stylesheet at all
// and therefore no variables, which is why it accumulated 269 hardcoded hex
// literals.
//
// So the tokens are emitted to a real .css file, imported by main.jsx (the
// ENTRY, not a lazy chunk -- a lazy import would land after first paint and
// every var() would resolve to `inherit` for a frame).
//
// The output is generated and committed. Do not hand-edit it; edit tokens.js.

import { writeFileSync, readFileSync, existsSync } from 'fs';
import { rootCss, TOKENS } from '../src/design/tokens.js';

const OUT = 'src/design/tokens.css';

const css = `/* GENERATED by scripts/gen-design-tokens.mjs -- do not edit.
   Source of truth: src/design/tokens.js
   Emitted here for the app entry, and inlined into the 191 static pages by
   gen-seo-pages.mjs, so both surfaces carry the same bytes. */
${rootCss()}
`;

const before = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
if (before !== css) {
  writeFileSync(OUT, css);
  console.log(`[design-tokens] wrote ${OUT} (${Object.keys(TOKENS).length} tokens)`);
} else {
  console.log(`[design-tokens] ${OUT} already current (${Object.keys(TOKENS).length} tokens)`);
}
