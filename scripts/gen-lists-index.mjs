// Emits src/marketing/listsIndex.js — {s: slug, h: h1, u: updated, n: rows}
// for every /lists/ page, so the front door can show "latest lists" without
// importing the 380KB lists.mjs (rows and prose) into the marketing bundle.
// Same shape of guard as gen-club-index.mjs: only rewrite when changed.
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { LISTS } from './seo/lists.mjs';
const OUT = 'src/marketing/listsIndex.js';
const rows = LISTS.map((l) => ({ s: l.slug, h: l.h1, u: l.updated || '', n: Array.isArray(l.rows) ? l.rows.length : 0 }))
  .sort((a, b) => (b.u || '').localeCompare(a.u || '') || a.h.localeCompare(b.h));
const body = `// GENERATED by scripts/gen-lists-index.mjs — do not edit. {s: slug, h: h1, u: verified date, n: rows}. ${rows.length} lists.
export const LISTS_INDEX = ${JSON.stringify(rows, null, 0).replace(/"([shun])":/g, '$1:').replace(/\},\{/g, '},\n{')};
`;
const before = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
if (before !== body) { writeFileSync(OUT, body); console.log(`[lists-index] wrote ${rows.length} lists → ${OUT}`); }
else console.log(`[lists-index] unchanged (${rows.length} lists)`);
