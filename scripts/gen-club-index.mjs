// Emits src/marketing/clubIndex.js — the Club Index rows for the Scouting
// Report homepage.
//
// WHY GENERATED. The marketing chunk must not import scripts/seo/clubs.mjs
// directly: that file carries every club's prose (intros, FAQs, descriptions)
// and would drag ~200KB of SEO copy into the homepage bundle to use three
// fields per club. This emits just {name, slug, competition} — and it runs in
// the build chain, so adding a club page updates the homepage index in the
// same build that creates the page. The heading count is generated too; the
// mockup hardcoded "Seventy-two" and that number is one Wave M away from
// being a lie.
//
// THE COLUMN IS THE HAND-VERIFIED ONE. competitionFor() prefers the exact
// roster match in leagues.mjs and falls back to club-competition.mjs, where
// every entry was checked by hand because fuzzy matching filed PSG under
// Paris FC and Leverkusen under Bayern Munich. If a club resolves to nothing,
// this script FAILS THE BUILD rather than emitting a blank — a new club page
// needs its competition decided, not defaulted.

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { CLUBS } from './seo/clubs.mjs';
import { LEAGUES } from './seo/leagues.mjs';
import { competitionFor } from './seo/club-competition.mjs';
import { clubColour } from '../src/lib/clubColour.js';

const OUT = 'src/marketing/clubIndex.js';

// Club colours live on CLUB_PACKS in src/App.jsx (JSX — not importable here).
// The packs are plain data literals, so read them as text: every pack carries
// `name: "…", icon: "…", color: "#……"` on one line. clubColour() then resolves
// the index's display names through the same alias table the app uses, so the
// front door's club cards get the colour the app would show, without the
// game bundle. A club with no match gets no `h` and renders a neutral dot.
const appSrc = readFileSync('src/App.jsx', 'utf8');
const packMap = {};
for (const m of appSrc.matchAll(/name:\s*"([^"]+)"[^\n]*?color:\s*"(#[0-9A-Fa-f]{6})"/g)) packMap[m[1]] = m[2];
if (Object.keys(packMap).length < 50) { console.error(`[club-index] only ${Object.keys(packMap).length} pack colours parsed from src/App.jsx — the CLUB_PACKS literal shape changed`); process.exit(1); }

const rows = CLUBS.map((c) => {
  const comp = competitionFor(c.club, LEAGUES);
  if (!comp) {
    console.error(`[club-index] ${c.slug} (${c.club}) has no competition — add it to scripts/seo/club-competition.mjs`);
    process.exit(1);
  }
  // c.name is the display form (Beşiktaş with diacritics); c.club is the
  // ASCII pack key. The index shows the display form.
  const h = clubColour(c.name, packMap) || clubColour(c.club, packMap) || null;
  return h ? { n: c.name, s: c.slug, c: comp, h } : { n: c.name, s: c.slug, c: comp };
}).sort((a, b) => a.n.localeCompare(b.n, 'en'));

// The heading spells the count out ("Seventy-two clubs on file"). Words up to
// 199 cover any plausible index size; beyond that the build fails loudly and
// someone writes the next band on purpose.
const ONES = ['zero','one','two','three','four','five','six','seven','eight','nine','ten','eleven','twelve','thirteen','fourteen','fifteen','sixteen','seventeen','eighteen','nineteen'];
const TENS = ['','','twenty','thirty','forty','fifty','sixty','seventy','eighty','ninety'];
function words(n) {
  if (n < 20) return ONES[n];
  if (n < 100) return TENS[Math.floor(n / 10)] + (n % 10 ? '-' + ONES[n % 10] : '');
  if (n < 200) return 'one hundred' + (n % 100 ? ' and ' + words(n % 100) : '');
  console.error(`[club-index] ${n} clubs — extend words() deliberately`);
  process.exit(1);
}
const count = rows.length;
const headingWord = words(count).replace(/^./, (ch) => ch.toUpperCase());

const body = `// GENERATED by scripts/gen-club-index.mjs — do not edit.
// Source of truth: scripts/seo/clubs.mjs + scripts/seo/club-competition.mjs.
// {n: display name, s: slug, c: competition, h: colour hex when known}. ${count} rows, alphabetical.

export const CLUB_HEADING = '${headingWord} clubs on file';

export const CLUB_INDEX = ${JSON.stringify(rows, null, 0).replace(/"([nsch])":/g, '$1:').replace(/\},\{/g, '},\n{')};
`;

const before = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
if (before !== body) {
  writeFileSync(OUT, body);
  console.log(`[club-index] wrote ${OUT} (${count} clubs, "${headingWord} clubs on file")`);
} else {
  console.log(`[club-index] ${OUT} already current (${count} clubs)`);
}
