// report-mystery-hints.mjs — the six hint cards for every curated answer, with
// the facts each rests on, for a person to read (R1: "hints have to be right").
//
//   node scripts/report-mystery-hints.mjs [out.md] [--json out.json]
//
// Prints the counts; writes every answer's cards to the markdown file. The
// year is the puzzle year of today's edition (running spells count to it).
import { readFileSync, writeFileSync } from 'fs';
import { withCareerFixes, careerOf, mainClub, spellYears } from '../src/lib/mysteryCareer.js';
import { hintCards, nationsOf } from '../src/lib/mysteryRules.js';

const read = (p) => JSON.parse(readFileSync(p, 'utf8'));
const pool = read('src/data/mysteryPool.json');
const answers = read('src/data/mysteryAnswers.json');
const careers = withCareerFixes(read('src/data/mysteryCareers.json'), read('src/data/mysteryCareerFixes.json'));
const ctx = {
  careers, byId: new Map(pool.map((p) => [p.id, p])), answers,
  nations: read('src/data/mysteryNations.json'), regions: read('src/data/nationRegions.json'),
  flags: read('src/data/nationFlags.json'), year: 2026,
};
const out = process.argv[2] && !process.argv[2].startsWith('--') ? process.argv[2] : null;
const jsonAt = process.argv.indexOf('--json');

const count = {};
const bump = (k) => { count[k] = (count[k] || 0) + 1; };
const lines = [];
const all = {};
const show = (c) => {
  if (!c.available) return `NOT OFFERED (${c.reason})`;
  const v = c.value;
  const lv = c.level !== 'main' ? ` [fallback: ${c.level}]` : '';
  switch (c.key) {
    case 'teammate': case 'teammateMain':
      return `${v.name} (${v.id}) at ${v.club}, together ${c.facts.together} (${c.facts.years} yrs)${lv}`;
    case 'club': return v.oneClub ? `one-club player (${c.facts.clubs.join(', ')})` : `${v.club} (${c.facts.spells.join(', ')}; never: ${c.facts.excluded.join(', ')})${lv}`;
    case 'careerYears': return `${v.from}–${v.to ?? 'now'} (first ${c.facts.first.club} ${spellYears(c.facts.first)}, last ${c.facts.last.club} ${spellYears(c.facts.last)})`;
    case 'nation': return `${v.nation}${v.flag ? '' : ' (NO FLAG)'}${c.facts.nations.length > 1 ? ` (all: ${c.facts.nations.join(', ')})` : ''}`;
    case 'birthYear': return `${v.year}${c.facts.dob ? ` (dob ${c.facts.dob})` : ' (no dob on file)'}`;
    default: return JSON.stringify(v);
  }
};

for (const id of answers) {
  const p = ctx.byId.get(id);
  if (!p) { bump('answer missing from pool'); continue; }
  const cards = hintCards(p, ctx);
  all[id] = cards;
  const career = careerOf(p, careers, ctx.year).map((s) => `${s.club} ${spellYears(s)}`).join('; ');
  lines.push(`### ${p.name} (${id}), born ${p.born}, ${p.slot}`);
  lines.push(`career: ${career || '(none)'} · main club: ${mainClub(p, careers, ctx.year) || '—'} · nations: ${nationsOf(p, ctx.nations).join(', ') || '—'}`);
  for (const r of [1, 2]) for (const c of cards[r]) {
    bump(`${c.key}: ${c.available ? (c.level === 'main' ? 'main rule' : `fallback ${c.level}`) : 'not offered'}`);
    if (!c.available) bump(`${c.key} not offered: ${c.reason.replace(/\d{4}/g, 'YYYY')}`);
    lines.push(`- R${r} ${c.key}: ${show(c)}`);
  }
  const offered = [1, 2].map((r) => cards[r].filter((c) => c.available).length);
  bump(`round 1 cards offered: ${offered[0]}`);
  bump(`round 2 cards offered: ${offered[1]}`);
  lines.push('');
}

const summary = Object.entries(count).sort().map(([k, v]) => `${k}: ${v}`);
console.log(summary.join('\n'));
if (out) writeFileSync(out, `# Mystery Player hint cards for the ${answers.length} curated answers\n\nPuzzle year ${ctx.year}. Generated by scripts/report-mystery-hints.mjs.\n\n## Counts\n\n${summary.map((s) => `- ${s}`).join('\n')}\n\n## Every answer\n\n${lines.join('\n')}\n`);
if (jsonAt > -1) writeFileSync(process.argv[jsonAt + 1], JSON.stringify(all));
